"""Generate a deterministic 1,000-file filename and folder test corpus."""
from __future__ import annotations

import argparse
import csv
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "fixtures" / "nonstandard-media-corpus"
VARIANTS = 50
EXTENSIONS = (".mkv", ".mp4", ".avi", ".m4v", ".m2ts")


def movie(title: str, filename: str, year: str = "", folder: str = "") -> tuple[str, str, str, str, int, int, int]:
    parent = folder or f"{title} ({year})" if year and folder == "" else folder
    relative = f"{parent}/{filename}" if parent else filename
    return relative, "电影", title, year, 0, 0, 0


def series(title: str, filename: str, season: int = 1, episode: int = 1,
           episode_end: int = 0, folder: str = "") -> tuple[str, str, str, str, int, int, int]:
    relative = f"{folder}/{filename}" if folder else filename
    return relative, "电视剧", title, "", season, episode, episode_end


def make_case(group: int, index: int) -> tuple[str, str, str, str, int, int, int]:
    number = f"{index:03d}"
    title = f"Movie Case {group:02d} {number}"
    tv_title = f"Series Case {group:02d} {number}"
    year = str(1980 + (index % 45))
    extension = EXTENSIONS[index % len(EXTENSIONS)]
    if group == 0:
        return movie(title, f"{title.replace(' ', '.')}.{year}{extension}", year)
    if group == 1:
        return movie(title, f"{title}{extension}", year, f"{title} ({year})")
    if group == 2:
        return movie(title, f"movie{extension}", year, f"{title} ({year})")
    if group == 3:
        tricky = f"2001 Odyssey Case {number}"
        return movie(tricky, f"{tricky} (1968){extension}", "1968")
    if group == 4:
        tricky = f"1917 Case {number}"
        return movie(tricky, f"{tricky} (2019){extension}", "2019")
    if group == 5:
        return movie(title, f"{title}.{year}.2160p.WEB-DL.DDP5.1.H.265-GROUP{extension}", year)
    if group == 6:
        return movie(title, f"[Release_Group] {title} [{year}] [1080p]{extension}", year)
    if group == 7:
        intl = f"中文电影 Édition {number}"
        return movie(intl, f"中文电影_Édition_{number}_{year}_简体中字{extension}", year)
    if group == 8:
        return movie(f"A Movie {number}", f"A.Movie.{number}.Extended.Cut{extension}")
    if group == 9:
        return movie("未知名称", f"1080p.WEB-DL.x265{extension}", folder=f"unidentified-{number}")
    if group == 10:
        episode = index % 99 + 1
        return series(tv_title, f"{tv_title.replace(' ', '.')}.S01E{episode:02d}.1080p.WEB-DL{extension}",
                      episode=episode)
    if group == 11:
        season, episode = index % 12, index % 99 + 1
        return series(tv_title, f"{tv_title}_s{season}_e{episode}{extension}", season, episode)
    if group == 12:
        season, episode = index % 12, index % 99 + 1
        return series(tv_title, f"{tv_title} {season}x{episode:02d}{extension}", season, episode)
    if group == 13:
        season, episode = index % 12, index % 99 + 1
        return series(tv_title, f"{tv_title} Season {season} Episode {episode}{extension}", season, episode)
    if group == 14:
        season, episode = index % 12, index % 99 + 1
        return series(tv_title, f"{tv_title}第{season}季第{episode}集{extension}", season, episode)
    if group == 15:
        episode = index % 99 + 1
        return series(tv_title, f"E{episode:02d}{extension}", 1, episode, folder=tv_title)
    if group == 16:
        season, episode = index % 12, index % 99 + 1
        return series(tv_title, f"第{episode:02d}集{extension}", season, episode,
                      folder=f"{tv_title}/Season {season:02d}")
    if group == 17:
        season, episode = index % 12, index % 99 + 1
        return series(tv_title, f"{episode:02d}{extension}", season, episode,
                      folder=f"{tv_title}/Season {season:02d}")
    if group == 18:
        season, episode = index % 12, index % 90 + 1
        end = episode + 2
        separator = ("-", "~", "+", "&", "E")[index % 5]
        return series(tv_title, f"{tv_title}.S{season:02d}E{episode:02d}{separator}{end:02d}{extension}",
                      season, episode, end)
    if group == 19:
        folder = "Series Case 19"
        episode = index + 1
        return series(folder, f"{episode:02d}{extension}", 1, episode, folder=folder)
    raise ValueError(f"Unknown group: {group}")


def generate(output: Path) -> int:
    marker = output / ".generated-fixtures"
    if output.exists():
        if not marker.exists():
            raise FileExistsError(f"拒绝覆盖没有生成标记的目录：{output}")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    marker.write_text("Generated by tests/generate_filename_corpus.py\n", encoding="utf-8")
    (output / "说明.txt").write_text(
        "本目录包含 1000 个零字节视频占位文件，仅用于测试文件名和目录扫描。\n"
        "文件不可播放。请将目录复制到独立测试源目录，只扫描并核对 manifest.csv；不要执行整理。\n",
        encoding="utf-8",
    )
    manifest_path = output / "manifest.csv"
    seen_paths: set[str] = set()
    with manifest_path.open("w", newline="", encoding="utf-8-sig") as manifest_file:
        writer = csv.writer(manifest_file)
        writer.writerow(("case_id", "group", "relative_path", "expected_kind", "expected_title",
                         "expected_year", "expected_season", "expected_episode", "expected_episode_end"))
        for group in range(20):
            for index in range(VARIANTS):
                case = make_case(group, index)
                relative, kind, title, year, season, episode, episode_end = case
                relative_path = Path(f"group-{group:02d}") / relative
                if relative_path.as_posix() in seen_paths:
                    raise ValueError(f"重复生成文件路径：{relative_path}")
                seen_paths.add(relative_path.as_posix())
                target = output / relative_path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.touch()
                writer.writerow((f"{group:02d}-{index:03d}", group, relative_path.as_posix(), kind,
                                 title, year, season, episode, episode_end))
    count = sum(1 for path in output.rglob("*") if path.is_file() and path.suffix.lower() in EXTENSIONS)
    expected_count = 20 * VARIANTS
    if count != expected_count:
        raise RuntimeError(f"语料数量不符：期望 {expected_count}，实际 {count}")
    return count


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    count = generate(args.output)
    archive = args.output.with_suffix(".zip")
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for path in args.output.rglob("*"):
            if path.is_file():
                bundle.write(path, path.relative_to(args.output.parent))
    print(f"生成 {count} 个空视频占位文件：{args.output}")
    print(f"预期清单：{args.output / 'manifest.csv'}")
    print(f"压缩包：{archive}")


if __name__ == "__main__":
    main()
